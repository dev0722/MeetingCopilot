import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it } from 'vitest';
import { AnswerSession, type AnswerTurn } from '../src/components/AnswerSession';
import { I18nProvider } from '../src/i18n';

function render(turn: AnswerTurn): string {
  const noop = () => {};
  return renderToStaticMarkup(createElement(I18nProvider, {
    lang: 'en',
    children: createElement(AnswerSession, {
      sessions: [],
      currentId: 'fixture',
      turns: [turn],
      resumeChars: 0,
      jdChars: 0,
      visionReady: false,
      answersReady: true,
      answersHint: '',
      onSwitch: noop,
      onNew: noop,
      onDelete: noop,
      onRename: noop,
      onPickKb: noop,
      onClearKb: noop,
      onCancel: noop,
      onRetry: noop,
      onClear: noop,
      onFreeAsk: noop,
      onShotAsk: noop,
    }),
  }));
}

describe('automatic reply presentation', () => {
  it('shows only the generated reply and reply translation', () => {
    const html = render({
      id: 'auto-1',
      kind: 'continuous',
      label: 'Could you explain the architecture?',
      text: 'I designed a multi-process pipeline.',
      status: 'done',
      autoGenerated: true,
      sourceSegmentId: 4,
      replyTranslation: '我设计了一套多进程流水线。',
      replyTranslationStatus: 'done',
    });

    expect(html).toContain('I designed a multi-process pipeline.');
    expect(html).toContain('我设计了一套多进程流水线。');
    expect(html).not.toContain('Could you explain the architecture?');
  });

  it('keeps translation failure separate from the generated reply', () => {
    const html = render({
      id: 'auto-2',
      kind: 'continuous',
      label: 'Source question',
      text: 'The answer is still useful.',
      status: 'done',
      autoGenerated: true,
      replyTranslationStatus: 'error',
    });

    expect(html).toContain('The answer is still useful.');
    expect(html).toContain('(reply translation failed)');
  });
});
